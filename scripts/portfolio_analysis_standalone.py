def run_strategy_benchmark(close, config):
    """Equal-weight buy-and-hold benchmark."""
    n = close.shape[1]
    entries = pd.DataFrame(False, index=close.index, columns=close.columns)
    exits = pd.DataFrame(False, index=close.index, columns=close.columns)
    entries.iloc[0] = True
    exits.iloc[-1] = True
   
    pf = vbt.Portfolio.from_signals(
        close=close.astype(float),
        entries=entries,
        exits=exits,
        init_cash=float(config["START_CASH"]),
        fees=float(config["FEES"]),
        slippage=float(config["SLIPPAGE"]),
        freq=config["FREQ"],
        size=1.0 / n,
        size_type="percent",
        cash_sharing=True,
        group_by=np.full(n, 0)
    )
    return pf

def main():
    parser = argparse.ArgumentParser(description="Portfolio Strategy Analysis Standalone")
    parser.add_argument("--results-dir", type=str, required=True, help="Path to WFO results")
    args = parser.parse_args()
   
    print(f"Loading results from {args.results_dir}...")
    per_coin_results, raw_config = load_wfo_results(args.results_dir)
   
    print("Loading OHLCV data...")
    ohlcv, _ = load_data_with_movers(raw_config)
   
    print("Generating combined signals...")
    entries, exits, close, robustness = generate_combined_signals(
        ohlcv, per_coin_results, raw_config
    )
   
    strategies = {}
    weights = {}
   
    print("Running Baseline (Current: Flat 10%)...")
    strategies["Flat 10%"], weights["Flat 10%"] = run_strategy_equal_share(
        close, entries, exits, raw_config, share=0.1
    )
   
    print("Running Max Diversified (1/N)...")
    strategies["Max Diversified (1/N)"], weights["Max Diversified (1/N)"] = run_strategy_max_diversified(
        close, entries, exits, raw_config
    )
   
    print("Running Volatility Weighted...")
    strategies["Volatility Weighted"], weights["Volatility Weighted"] = run_strategy_volatility_weighted(
        close, entries, exits, raw_config
    )
   
    print("Running Robustness Weighted...")
    strategies["Robustness Weighted"], weights["Robustness Weighted"] = run_strategy_robustness_weighted(
        close, entries, exits, raw_config, robustness
    )
   
    print("Running Buy & Hold Benchmark...")
    strategies["Buy & Hold (EW)"], _ = run_strategy_benchmark(close, raw_config)
   
    # Comparison table
    stats = []
    for name, pf in strategies.items():
        s = pf.stats()
        stats.append({
            "Strategy": name,
            "Total Return [%]": s['Total Return [%]'],
            "Sharpe Ratio": s['Sharpe Ratio'],
            "Sortino Ratio": s['Sortino Ratio'],
            "Max Drawdown [%]": s['Max Drawdown [%]'],
            "Win Rate [%]": s['Win Rate [%]'],
            "Profit Factor": s['Profit Factor'],
            "Expectancy": s['Expectancy'],
            "Total Trades": s['Total Trades']
        })
   
    df_stats = pd.DataFrame(stats)
    df_stats = df_stats.sort_values("Sharpe Ratio", ascending=False)
   
    print("\n--- Strategy Competition Results ---")
    print(df_stats.to_markdown(index=False))
   
    # Save results
    output_dir = Path(args.results_dir) / "portfolio_analysis"
    output_dir.mkdir(exist_ok=True)
    df_stats.to_csv(output_dir / "comparison_stats.csv", index=False)
    
    # Plots
    print("Generating plots...")
    vbt.settings.set_theme('dark')
    
    # Combine values for equity curve comparison
    values = pd.DataFrame({name: pf.value() for name, pf in strategies.items()})
    fig = values.vbt.plot(title="Portfolio Equity Comparison")
    fig.write_html(str(output_dir / "equity_comparison.html"))
    
    # Combined Drawdowns
    drawdowns = pd.DataFrame({name: pf.drawdown() for name, pf in strategies.items()})
    fig_dd = drawdowns.vbt.plot(title="Portfolio Drawdown Comparison")
    fig_dd.write_html(str(output_dir / "drawdown_comparison.html"))
    
    print(f"\nAnalysis complete. Results and plots saved to {output_dir}")
    
    # Export best weights
    best_strat_name = df_stats.iloc[0]["Strategy"]
    if best_strat_name in weights:
        best_weights = weights[best_strat_name]
        # Take the last valid weight for each symbol
        latest_weights = best_weights.iloc[-1].to_dict()
        
        weight_file = output_dir / "portfolio_weights.json"
        with open(weight_file, 'w') as f:
            json.dump({
                "strategy": best_strat_name,
                "timestamp": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
                "weights": latest_weights
            }, f, indent=4)
        print(f"Exported weights for '{best_strat_name}' to {weight_file}")

if __name__ == "__main__":
    main()
