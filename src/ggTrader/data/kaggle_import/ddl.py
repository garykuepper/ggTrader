def apply_ddl(conn: PgConnection) -> None:
    """Apply the schema in one transaction."""
    sql = (REPO_ROOT / "sql" / "kaggle_schema.sql").read_text(encoding="utf-8")
    with conn.cursor() as cur:
        cur.execute(sql)
    conn.commit()
